create table if not exists public.fiyatlar (
  il text primary key,
  benzin_95 text not null,
  motorin text not null,
  lpg text not null,
  guncelleme text
);

create table if not exists public.gecmis (
  id bigint generated by default as identity primary key,
  tarih date not null,
  benzin_95 text not null,
  motorin text not null,
  lpg text not null,
  benzin_degisim text not null default '0.00',
  motorin_degisim text not null default '0.00',
  lpg_degisim text not null default '0.00'
);

alter table public.fiyatlar enable row level security;
alter table public.gecmis enable row level security;

-- Mobil yalnızca okur; yazma backend'de service_role ile yapılır.
revoke all on public.fiyatlar from anon, authenticated;
revoke all on public.gecmis from anon, authenticated;
grant select on public.fiyatlar to anon, authenticated;
grant select on public.gecmis to anon, authenticated;
grant all on public.fiyatlar to service_role;
grant all on public.gecmis to service_role;
revoke all on sequence public.gecmis_id_seq from anon, authenticated;
grant usage, select on sequence public.gecmis_id_seq to service_role;

drop policy if exists "fiyatlar_select_anon" on public.fiyatlar;
