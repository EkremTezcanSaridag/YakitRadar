-- Bekleyen fiyat bildirimleri (sessiz saat kuyrugu). Murat: Supabase SQL editor'de calistirin.

create table if not exists public.pending_price_notifications (
  id bigint generated by default as identity primary key,
  dedupe_key text not null unique,
  change_payload jsonb not null,
  detected_at timestamptz not null default now(),
  sent_at timestamptz,
  created_at timestamptz not null default now()
);

create index if not exists pending_price_notifications_unsent_idx
  on public.pending_price_notifications (detected_at)
  where sent_at is null;

alter table public.pending_price_notifications enable row level security;

revoke all on public.pending_price_notifications from anon, authenticated;
revoke all on sequence public.pending_price_notifications_id_seq from anon, authenticated;

grant all on public.pending_price_notifications to service_role;
grant usage, select on sequence public.pending_price_notifications_id_seq to service_role;

drop policy if exists "pending_price_notifications_insert_anon" on public.pending_price_notifications;
drop policy if exists "pending_price_notifications_update_anon" on public.pending_price_notifications;
drop policy if exists "pending_price_notifications_delete_anon" on public.pending_price_notifications;
drop policy if exists "pending_price_notifications_select_anon" on public.pending_price_notifications;
drop policy if exists "pending_price_notifications_all_anon" on public.pending_price_notifications;
drop policy if exists "pending_price_notifications_insert_authenticated" on public.pending_price_notifications;
drop policy if exists "pending_price_notifications_update_authenticated" on public.pending_price_notifications;
drop policy if exists "pending_price_notifications_delete_authenticated" on public.pending_price_notifications;
drop policy if exists "pending_price_notifications_select_authenticated" on public.pending_price_notifications;
drop policy if exists "pending_price_notifications_all_authenticated" on public.pending_price_notifications;
